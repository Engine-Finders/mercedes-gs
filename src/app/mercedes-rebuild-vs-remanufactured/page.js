import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/mercedes-rebuild-vs-remanufactured.json";

const PATH = "/mercedes-rebuild-vs-remanufactured";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Mercedes-Benz Rebuild vs Remanufactured | Mercedes Garage",
  description: "Compare engine rebuild vs remanufactured for Mercedes-Benz. Understand the process differences, warranty implications, and which option suits your vehicle and budget.",
  alternates: { canonical: PATH },
};

export default function MercedesRebuildVsRemanufacturedPage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/mercedes-engine-rebuild" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
