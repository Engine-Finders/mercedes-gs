import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/mercedes-diesel-timing-chain-repair.json";

const PATH = "/mercedes-diesel-timing-chain-repair";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Mercedes Diesel Timing Chain & Injector Repair | Mercedes Garage",
  description: "Specialist Mercedes diesel timing chain and injector seal repair for OM-series engines. Fixed-price rebuilds from £2,200. Nationwide recovery and 12-month warranty.",
  alternates: { canonical: PATH },
};

export default function MercedesDieselTimingChainRepairPage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/mercedes-engine-rebuild" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
